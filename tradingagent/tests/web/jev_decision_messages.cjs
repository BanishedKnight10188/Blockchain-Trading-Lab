"use strict";
const fs=require("node:fs"),vm=require("node:vm"),assert=require("node:assert/strict");
const scope=vm.createContext({window:{}});
vm.runInContext(fs.readFileSync("agent_platform/web/static/jev-decision-messages.js","utf8"),scope);
const messages=scope.window.JevDecisionMessages;
assert.equal(messages.diagnosticFor("provider_timeout_retry",[{reason:"invalid_model_assessment",diagnostic:{stage:"answer_values"}},{reason:"provider_timeout",diagnostic:{stage:"transport"}}]).stage,"transport");
assert.match(messages.failure("provider_timeout",null,{consecutive_timeouts:1,retrying:true}),/冷却.*新行情/);
assert.match(messages.failure("provider_timeout",null,{consecutive_timeouts:3,retrying:false}),/连续 3 次.*已暂停/);
assert.match(messages.failure("provider_timeout",{stage:"transport",transport_evidence:{failed_phase:"tls"}}),/加密连接.*已暂停/);
assert.match(messages.failure("provider_timeout",{stage:"transport",transport_evidence:{failed_phase:"response_wait"}}),/等待模型响应.*已暂停/);
assert.match(messages.failure("provider_timeout",null),/请求等待超时/);
assert.match(messages.failure("decision_expired",{stage:"binding",local_timing:{settle_us:3000000}}),/费用记录.*继续/);
assert.match(messages.failure("decision_expired",null),/决策已过期/);
assert.match(messages.failure("invalid_model_assessment",{stage:"answer_values"}),/数值/);
assert.doesNotMatch(messages.failure("invalid_model_assessment",{stage:"answer_values"}),/检查连接/);
assert.match(messages.failure("invalid_model_assessment",{stage:"answer_values",issue:"probability_sum",probability_total:"0.98"}),/0\.98/);
assert.match(messages.result({status:"wait",choice_probability_adjustments:[{original_total:"0.99"}]}),/0\.99/);
assert.match(messages.result({status:"rejected",reason:"invalid_model_assessment",diagnostic:{stage:"criteria"}}),/选项/);
assert.match(messages.market({failure:"futures_stream_future",event_ahead_ms:307}),/时钟.*307/);
assert.doesNotMatch(messages.market({failure:"futures_stream_future",event_ahead_ms:307}),/检查连接/);
assert.match(messages.market({clock:{ready:false,failure:"clock_calibration_stale"}}),/校时/);
assert.match(messages.market({connected:{book:true,mark:true},recent_quote_count:3,clock:{ready:true,offset_ms:410}}),/已恢复/);
assert.match(messages.clock({ready:true,offset_ms:410,uncertainty_ms:30}),/自动校时.*410.*30/);
console.log("PASS: model and market failures identify their actual cause");
